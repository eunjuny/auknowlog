CREATE TABLE quality_evaluation_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_type VARCHAR(32) NOT NULL,
    source_key VARCHAR(255),
    model VARCHAR(128),
    prompt_version VARCHAR(64),
    status VARCHAR(32) NOT NULL,
    candidate_count INTEGER NOT NULL DEFAULT 0,
    review_required_count INTEGER NOT NULL DEFAULT 0,
    input_tokens BIGINT,
    output_tokens BIGINT,
    total_tokens BIGINT,
    failure_type VARCHAR(64),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT ck_quality_evaluation_type CHECK (
        evaluation_type IN ('DUPLICATE_THRESHOLD', 'OBJECTIVE_QUALITY')
    ),
    CONSTRAINT ck_quality_evaluation_status CHECK (
        status IN ('RUNNING', 'COMPLETED', 'FAILED')
    )
);

CREATE TABLE duplicate_question_pair (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_a_id BIGINT NOT NULL REFERENCES question_history(id) ON DELETE CASCADE,
    question_b_id BIGINT NOT NULL REFERENCES question_history(id) ON DELETE CASCADE,
    human_verdict VARCHAR(32),
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_duplicate_pair_order CHECK (question_a_id < question_b_id),
    CONSTRAINT ck_duplicate_pair_human_verdict CHECK (
        human_verdict IS NULL OR human_verdict IN ('DUPLICATE', 'RELATED', 'DISTINCT', 'SKIPPED')
    ),
    CONSTRAINT uk_duplicate_question_pair UNIQUE (question_a_id, question_b_id)
);

CREATE TABLE duplicate_evaluation_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES quality_evaluation_run(id) ON DELETE CASCADE,
    pair_id BIGINT NOT NULL REFERENCES duplicate_question_pair(id) ON DELETE CASCADE,
    similarity DOUBLE PRECISION NOT NULL,
    embedding_model VARCHAR(128) NOT NULL,
    system_verdict VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_duplicate_similarity CHECK (similarity BETWEEN -1 AND 1),
    CONSTRAINT ck_duplicate_system_verdict CHECK (
        system_verdict IN ('DUPLICATE', 'REVIEW_REQUIRED', 'DISTINCT')
    ),
    CONSTRAINT uk_duplicate_result_run_pair UNIQUE (run_id, pair_id)
);

CREATE TABLE objective_evaluation_case (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES quality_evaluation_run(id) ON DELETE CASCADE,
    case_type VARCHAR(32) NOT NULL,
    topic VARCHAR(255) NOT NULL,
    reference_key VARCHAR(64),
    reference_title VARCHAR(255),
    importance VARCHAR(16),
    learning_objective_id BIGINT REFERENCES learning_objective(id) ON DELETE SET NULL,
    learning_question_id BIGINT REFERENCES learning_question(id) ON DELETE SET NULL,
    ai_verdict VARCHAR(32) NOT NULL,
    ai_confidence DOUBLE PRECISION NOT NULL,
    ai_rationale TEXT NOT NULL,
    human_verdict VARCHAR(32),
    review_status VARCHAR(32) NOT NULL,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_objective_case_type CHECK (
        case_type IN ('OBJECTIVE_COVERAGE', 'QUESTION_ALIGNMENT')
    ),
    CONSTRAINT ck_objective_importance CHECK (
        importance IS NULL OR importance IN ('CORE', 'SUPPORTING')
    ),
    CONSTRAINT ck_objective_ai_verdict CHECK (
        ai_verdict IN ('COVERED', 'PARTIAL', 'MISSING', 'ALIGNED', 'MISALIGNED')
    ),
    CONSTRAINT ck_objective_ai_confidence CHECK (ai_confidence BETWEEN 0 AND 1),
    CONSTRAINT ck_objective_human_verdict CHECK (
        human_verdict IS NULL OR human_verdict IN (
            'COVERED', 'PARTIAL', 'MISSING', 'ALIGNED', 'MISALIGNED', 'SKIPPED'
        )
    ),
    CONSTRAINT ck_objective_review_status CHECK (
        review_status IN ('AUTO_ACCEPTED', 'REVIEW_REQUIRED', 'REVIEWED')
    )
);

CREATE INDEX idx_quality_evaluation_run_created
    ON quality_evaluation_run (created_at DESC);
CREATE INDEX idx_duplicate_pair_review
    ON duplicate_question_pair (human_verdict, created_at DESC);
CREATE INDEX idx_duplicate_result_pair_created
    ON duplicate_evaluation_result (pair_id, created_at DESC);
CREATE INDEX idx_objective_case_review
    ON objective_evaluation_case (review_status, created_at DESC);
CREATE INDEX idx_objective_case_run
    ON objective_evaluation_case (run_id);
