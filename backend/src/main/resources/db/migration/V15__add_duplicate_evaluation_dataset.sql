CREATE TABLE duplicate_evaluation_dataset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_key VARCHAR(64) NOT NULL,
    title VARCHAR(255) NOT NULL,
    dataset_version VARCHAR(32) NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    embedding_model VARCHAR(128),
    embedding_input_tokens BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    embedded_at TIMESTAMP,
    CONSTRAINT uk_duplicate_evaluation_dataset_key UNIQUE (dataset_key),
    CONSTRAINT ck_duplicate_evaluation_dataset_source CHECK (
        source_type IN ('CURATED_REFERENCE')
    ),
    CONSTRAINT ck_duplicate_evaluation_dataset_status CHECK (
        status IN ('DRAFT', 'PROCESSING', 'READY', 'FAILED')
    )
);

CREATE TABLE duplicate_evaluation_dataset_sample (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL REFERENCES duplicate_evaluation_dataset(id) ON DELETE CASCADE,
    sample_order INTEGER NOT NULL,
    topic VARCHAR(255) NOT NULL,
    question_a TEXT NOT NULL,
    question_b TEXT NOT NULL,
    reference_verdict VARCHAR(32) NOT NULL,
    reference_rationale TEXT NOT NULL,
    embedding_a vector(512),
    embedding_b vector(512),
    similarity DOUBLE PRECISION,
    embedding_model VARCHAR(128),
    reviewer_verdict VARCHAR(32),
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_duplicate_evaluation_dataset_sample UNIQUE (dataset_id, sample_order),
    CONSTRAINT ck_duplicate_dataset_reference_verdict CHECK (
        reference_verdict IN ('DUPLICATE', 'RELATED', 'DISTINCT')
    ),
    CONSTRAINT ck_duplicate_dataset_reviewer_verdict CHECK (
        reviewer_verdict IS NULL OR reviewer_verdict IN ('DUPLICATE', 'RELATED', 'DISTINCT', 'SKIPPED')
    ),
    CONSTRAINT ck_duplicate_dataset_similarity CHECK (
        similarity IS NULL OR similarity BETWEEN -1 AND 1
    )
);

CREATE INDEX idx_duplicate_dataset_sample_dataset
    ON duplicate_evaluation_dataset_sample (dataset_id, sample_order);
CREATE INDEX idx_duplicate_dataset_sample_reference
    ON duplicate_evaluation_dataset_sample (dataset_id, reference_verdict);
