CREATE TABLE learning_roadmap_step (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roadmap_id BIGINT NOT NULL,
    step_key VARCHAR(64) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    topic VARCHAR(255) NOT NULL,
    question_target INTEGER NOT NULL,
    step_order INTEGER NOT NULL,
    major_topic_key VARCHAR(64) NOT NULL,
    major_topic_title VARCHAR(255) NOT NULL,
    major_topic_description TEXT,
    major_topic_topic VARCHAR(255) NOT NULL,
