    CONSTRAINT uk_learning_roadmap_step_key UNIQUE (roadmap_id, step_key),
    CONSTRAINT uk_learning_roadmap_step_order UNIQUE (roadmap_id, step_order),
    CONSTRAINT fk_learning_roadmap_step_roadmap FOREIGN KEY (roadmap_id) REFERENCES learning_roadmap(id) ON DELETE CASCADE
